// rust/CATALOG.md: the component library as one compact file for people and
// AI agents — every Rust component with its import, props, stories and what
// it is for, generated from rust/library.ts, the components' Props and the
// stories. UPDATE_CATALOG=1 rewrites it; otherwise this fails when it's stale.
import { expect, test } from 'vitest'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'
import { RUST_LIBRARY } from '../../rust/library'

const APP = resolve(__dirname, '../..')
const STORYBOOK = 'https://my.minmatar.org/rust/'

const story_sources = import.meta.glob<string>('../../rust/stories/**/*.stories.ts', { eager: true, query: '?raw', import: 'default' })
const story_modules = import.meta.glob<Record<string, any>>('../../rust/stories/**/*.stories.ts')

interface Prop { name: string; type: string; optional: boolean; default?: string; note?: string }

function read_props(component: string): Prop[] {
    const source = readFileSync(resolve(APP, 'src/components', `${component}.astro`), 'utf8')
    const frontmatter = source.split('---')[1] ?? ''
    const body = /interface Props\s*\{([\s\S]*?)\n\}/.exec(frontmatter)?.[1] ?? ''
    const props: Prop[] = []
    let note: string | undefined
    for (const raw of body.split('\n')) {
        const line = raw.trim()
        const comment = /^\/\*\*?\s*(.*?)\s*\*?\/?$|^\/\/\s*(.*)$/.exec(line)
        if (line.startsWith('/') || line.startsWith('*')) {
            note = (comment?.[1] || comment?.[2] || '').replace(/\*\/$/, '').trim() || note
            continue
        }
        const m = /^['"]?([\w-]+)['"]?(\?)?\s*:\s*(.+?)[;,]?\s*(?:\/\/\s*(.*))?$/.exec(line)
        if (!m || m[1] === 'propName')
            continue
        props.push({ name: m[1], type: m[3].trim(), optional: Boolean(m[2]), note: m[4] ?? note })
        note = undefined
    }
    // Defaults from the destructuring: `name = value,`
    const destructure = /=\s*Astro\.props/.test(frontmatter) ? frontmatter : ''
    for (const prop of props) {
        const d = new RegExp(`\\b${prop.name}\\s*=\\s*([^,\\n]+),?\\n`).exec(destructure)
        if (d) prop.default = d[1].trim()
    }
    return props
}

function stories_file_for(component: string) {
    for (const [path, source] of Object.entries(story_sources)) {
        const covers = /covers:\s*'([^']+)'/.exec(source)?.[1]
        const meta = /export default \{([\s\S]*?)\n\}/.exec(source)?.[1] ?? ''
        const name = /^\s{4}component:\s*(\w+)/m.exec(meta)?.[1]
        const imported = name ? new RegExp(`import\\s+${name}\\s+from\\s+['"]@components/([^'"]+?)(?:\\.astro)?['"]`).exec(source)?.[1] : undefined
        if (covers === component || imported === component)
            return path
    }
    return undefined
}

const one_line = (text: string) => text.replace(/\s+/g, ' ').trim()
// The first sentence, not split at abbreviations like "e.g." or "i.e.".
const first_sentence = (text: string) => one_line(text).split(/(?<!\b(?:e\.g|i\.e|etc|vs))(?<=\.)\s(?=[A-Z`*])/)[0]
const story_id = (title: string, name = 'docs') =>
    `${title.toLowerCase().replace(/[^a-z0-9/]+/g, '-').replace(/\//g, '-').replace(/-+/g, '-')}--${name}`

async function build() {
    const lines: string[] = [
        '# Rust component catalog',
        '',
        '<!-- Generated by testing/rust/catalog.test.ts (UPDATE_CATALOG=1). Do not edit by hand. -->',
        '',
        `Every shared component in Rust, the Minmatar Fleet component library (${STORYBOOK}), with its import, props and stories.`,
        'Reach for these before writing markup or CSS of your own; each stories file is the canonical usage example.',
        'Props: `name?: type = default`; `slots` are the named `<slot>`s the stories fill. Conventions: `docs/frontend-design.md`.',
        '',
    ]
    for (const [category, components] of Object.entries(RUST_LIBRARY)) {
        lines.push(`## ${category}`, '')
        for (const component of components) {
            const name = component.split('/').pop()!
            const path = stories_file_for(component)
            const mod = path ? await story_modules[path]() : undefined
            const meta = mod?.default ?? {}
            const description = meta.parameters?.docs?.description?.component ?? ''
            const stories = Object.entries(mod ?? {})
                .filter(([key, value]) => key !== 'default' && !key.startsWith('__') && value && typeof value === 'object')
                .map(([key, value]: [string, any]) => value.name ?? key.replace(/([a-z])([A-Z])/g, '$1 $2'))
            const props = read_props(component)
            const slots = [...new Set([...readFileSync(resolve(APP, 'src/components', `${component}.astro`), 'utf8').matchAll(/<slot(?:\s+name="([\w-]+)")?/g)].map((m) => m[1] ?? 'default'))]

            lines.push(`### ${name}`)
            lines.push('')
            if (description) lines.push(first_sentence(description), '')
            lines.push(`- Import: \`import ${name} from '@components/${component}.astro'\``)
            if (props.length)
                lines.push(`- Props: ${props.map((p) => `\`${p.name}${p.optional ? '?' : ''}: ${p.type}${p.default ? ` = ${p.default}` : ''}\``).join(', ')}`)
            if (slots.length)
                lines.push(`- Slots: ${slots.map((s) => `\`${s}\``).join(', ')}`)
            if (path && meta.title)
                lines.push(`- Stories (${stories.length}): \`${path.replace('../../', 'frontend/app/')}\`, ${STORYBOOK}?path=/docs/${story_id(meta.title)}: ${stories.join(', ')}`)
            lines.push('')
        }
    }
    // Features: feature blocks with fixture data, by area. Not part of the
    // library; listed so an agent building a feature finds the data shapes.
    const features = Object.entries(story_sources)
        .filter(([path]) => path.includes('/rust/stories/features/'))
        .sort(([a], [b]) => a.localeCompare(b))
    if (features.length) {
        lines.push('## Features (feature blocks with test data)', '')
        lines.push('Not reusable components: the site\'s feature blocks rendered from typed fixtures, one story per scenario. Reuse the fixtures for realistic data.', '')
        for (const [path, source] of features) {
            const mod = await story_modules[path]()
            const meta = mod.default ?? {}
            const fixtures = [...new Set([...source.matchAll(/from\s+['"]([^'"]*fixtures\/features\/[^'"]+)['"]/g)].map((m) => m[1].replace(/^(\.\.\/)+/, 'frontend/app/rust/')))]
            const stories = Object.entries(mod)
                .filter(([key, value]) => key !== 'default' && !key.startsWith('__') && value && typeof value === 'object')
                .map(([key, value]: [string, any]) => value.name ?? key.replace(/([a-z])([A-Z])/g, '$1 $2'))
            lines.push(`- **${meta.title?.replace(/^Features\//, '')}**: \`${path.replace('../../', 'frontend/app/')}\`${fixtures.length ? `, fixtures ${fixtures.map((f) => `\`${f}\``).join(', ')}` : ''}. Scenarios: ${stories.join(', ')}`)
        }
        lines.push('')
    }

    return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

test('rust/CATALOG.md lists every library component (UPDATE_CATALOG=1 rewrites it)', async () => {
    const path = resolve(APP, 'rust/CATALOG.md')
    const expected = await build()
    if (process.env.UPDATE_CATALOG || !existsSync(path))
        writeFileSync(path, expected)
    expect(readFileSync(path, 'utf8'), 'run UPDATE_CATALOG=1 npx vitest run testing/rust/catalog.test.ts').toBe(expected)
}, 120_000) // imports every stories module
